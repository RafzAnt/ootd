-- OOTD Supabase schema
-- Paste this into Supabase Dashboard > SQL Editor and run it once on a new project.
-- It creates the Laravel tables and records the matching migrations so that
-- `php artisan migrate --force` will not try to create these tables again.

begin;

create table if not exists public.users (
    id bigint generated by default as identity primary key,
    name varchar(255) not null,
    email varchar(255) not null unique,
    email_verified_at timestamp without time zone null,
    password varchar(255) not null,
    remember_token varchar(100) null,
    reminders_enabled boolean not null default true,
    reminder_time varchar(5) not null default '18:00',
    last_reminder_on date null,
    created_at timestamp without time zone null,
    updated_at timestamp without time zone null
);

create table if not exists public.password_reset_tokens (
    email varchar(255) primary key,
    token varchar(255) not null,
    created_at timestamp without time zone null
);

create table if not exists public.sessions (
    id varchar(255) primary key,
    user_id bigint null,
    ip_address varchar(45) null,
    user_agent text null,
    payload text not null,
    last_activity integer not null
);

create index if not exists sessions_user_id_index on public.sessions (user_id);
create index if not exists sessions_last_activity_index on public.sessions (last_activity);

create table if not exists public.cache (
    key varchar(255) primary key,
    value text not null,
    expiration bigint not null
);

create index if not exists cache_expiration_index on public.cache (expiration);

create table if not exists public.cache_locks (
    key varchar(255) primary key,
    owner varchar(255) not null,
    expiration bigint not null
);

create index if not exists cache_locks_expiration_index on public.cache_locks (expiration);

create table if not exists public.jobs (
    id bigint generated by default as identity primary key,
    queue varchar(255) not null,
    payload text not null,
    attempts smallint not null,
    reserved_at integer null,
    available_at integer not null,
    created_at integer not null
);

create index if not exists jobs_queue_index on public.jobs (queue);

create table if not exists public.job_batches (
    id varchar(255) primary key,
    name varchar(255) not null,
    total_jobs integer not null,
    pending_jobs integer not null,
    failed_jobs integer not null,
    failed_job_ids text not null,
    options text null,
    cancelled_at integer null,
    created_at integer not null,
    finished_at integer null
);

create table if not exists public.failed_jobs (
    id bigint generated by default as identity primary key,
    uuid varchar(255) not null unique,
    connection varchar(255) not null,
    queue varchar(255) not null,
    payload text not null,
    exception text not null,
    failed_at timestamp without time zone not null default current_timestamp
);

create index if not exists failed_jobs_connection_queue_failed_at_index
    on public.failed_jobs (connection, queue, failed_at);

create table if not exists public.ootds (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users (id) on delete cascade,
    image_path varchar(255) not null,
    description text null,
    occasion varchar(32) null,
    is_favorite boolean not null default false,
    created_at timestamp without time zone null,
    updated_at timestamp without time zone null
);

create index if not exists ootds_user_id_created_at_index
    on public.ootds (user_id, created_at);

create table if not exists public.notifications (
    id uuid primary key,
    type varchar(255) not null,
    notifiable_type varchar(255) not null,
    notifiable_id bigint not null,
    data text not null,
    read_at timestamp without time zone null,
    created_at timestamp without time zone null,
    updated_at timestamp without time zone null
);

create index if not exists notifications_notifiable_type_notifiable_id_index
    on public.notifications (notifiable_type, notifiable_id);

create table if not exists public.wear_logs (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users (id) on delete cascade,
    ootd_id bigint not null references public.ootds (id) on delete cascade,
    worn_on date not null,
    created_at timestamp without time zone null,
    updated_at timestamp without time zone null,
    constraint wear_logs_user_id_worn_on_unique unique (user_id, worn_on)
);

create index if not exists wear_logs_ootd_id_worn_on_index
    on public.wear_logs (ootd_id, worn_on);

create table if not exists public.outfit_plans (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users (id) on delete cascade,
    ootd_id bigint not null references public.ootds (id) on delete cascade,
    planned_for date not null,
    created_at timestamp without time zone null,
    updated_at timestamp without time zone null,
    constraint outfit_plans_user_id_planned_for_unique unique (user_id, planned_for)
);

create index if not exists outfit_plans_ootd_id_planned_for_index
    on public.outfit_plans (ootd_id, planned_for);

create table if not exists public.migrations (
    id bigint generated by default as identity primary key,
    migration varchar(255) not null,
    batch integer not null
);

insert into public.migrations (migration, batch)
select pending.migration, 1
from (values
    ('0001_01_01_000000_create_users_table'),
    ('0001_01_01_000001_create_cache_table'),
    ('0001_01_01_000002_create_jobs_table'),
    ('2026_10_26_000000_create_ootds_table'),
    ('2026_10_26_124933_create_notifications_table'),
    ('2026_10_27_000000_add_picker_fields_to_ootds_table'),
    ('2026_10_27_000001_add_reminder_settings_to_users_table'),
    ('2026_11_02_091921_create_outfit_plans_table')
) as pending(migration)
where not exists (
    select 1 from public.migrations as applied where applied.migration = pending.migration
);

-- Keep the Supabase Data API from exposing app tables directly. Laravel connects
-- server-side with the postgres database role, which can access these tables.
alter table public.users enable row level security;
alter table public.password_reset_tokens enable row level security;
alter table public.sessions enable row level security;
alter table public.cache enable row level security;
alter table public.cache_locks enable row level security;
alter table public.jobs enable row level security;
alter table public.job_batches enable row level security;
alter table public.failed_jobs enable row level security;
alter table public.ootds enable row level security;
alter table public.notifications enable row level security;
alter table public.wear_logs enable row level security;
alter table public.outfit_plans enable row level security;
alter table public.migrations enable row level security;

commit;
